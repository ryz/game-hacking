"""Deep Dungeon III floor maps from the ROM -> design/maps/*.png (+ text grids).

Usage: python3 games/deep-dungeon-3/tools/maps.py [--rom rom/deep-dungeon-3.nes] [--out games/deep-dungeon-3/design/maps]

Format (playbook "Maps"): every dungeon floor is a 32x32 grid of one byte per square, stored raw in the
area's PRG bank at $9800 (odd floor) / $9C00 (even floor); the towns share one 32x48 grid in bank 9 at $9700.
The game copies the current grid to battery RAM $6100 (+ y*32 + x). Square bytes: $80 wall (bit 7 = solid),
$00 floor, $C0 door, $C8 shut door, $40 stairs up, $41 stairs down, other values = event squares (number).
"""
import argparse, os
from PIL import Image, ImageDraw

# area (RAM $7003) -> list of (floor, 16 KiB bank, offset in bank)
AREAS = {1: [(1, 1, 0x1800), (2, 1, 0x1C00)],
         2: [(1, 2, 0x1800), (2, 2, 0x1C00), (3, 3, 0x1800), (4, 3, 0x1C00)],
         3: [(1, 4, 0x1800), (2, 4, 0x1C00), (3, 5, 0x1800), (4, 5, 0x1C00), (5, 6, 0x1800), (6, 6, 0x1C00)],
         4: [(1, 7, 0x1800), (2, 7, 0x1C00), (3, 8, 0x1800), (4, 8, 0x1C00)]}
TOWN = (9, 0x1700, 48)

COL = {0x80: (60, 60, 140), 0x00: (235, 235, 225), 0xC0: (40, 120, 255), 0xC8: (200, 60, 60),
       0x40: (40, 200, 40), 0x41: (0, 130, 0)}

def char(v):
    if v == 0x80: return '#'
    if v == 0x00: return '.'
    return {0xC0: 'D', 0xC8: 'd', 0x40: '<', 0x41: '>'}.get(v, None)

def draw(grid, w, h, path, title):
    S = 16
    im = Image.new('RGB', (w * S + 24, h * S + 40), (20, 20, 20))
    d = ImageDraw.Draw(im)
    d.text((4, 2), title, fill=(255, 255, 0))
    for i in range(w):
        d.text((24 + i * S + 2, 14), '%d' % (i % 10), fill=(160, 160, 160))
    for y in range(h):
        d.text((2, 28 + y * S + 3), '%2d' % y, fill=(160, 160, 160))
        for x in range(w):
            v = grid[y * w + x]
            x0, y0 = 24 + x * S, 28 + y * S
            c = COL.get(v, (250, 200, 60) if v < 0x40 else (240, 120, 200))
            d.rectangle([x0, y0, x0 + S - 1, y0 + S - 1], fill=c, outline=(110, 110, 110))
            if v not in COL:
                d.text((x0 + 1, y0 + 3), '%02X' % v, fill=(0, 0, 0))
            elif v in (0x40, 0x41):
                d.text((x0 + 4, y0 + 3), 'U' if v == 0x40 else 'D', fill=(255, 255, 255))
    im.save(path)

def text(grid, w, h):
    out = []
    for y in range(h):
        row = ''
        for x in range(w):
            v = grid[y * w + x]; c = char(v)
            row += c if c else ('%X' % v if v < 16 else '*')
        out.append('%2d %s' % (y, row))
    return '\n'.join(out)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rom', default='rom/deep-dungeon-3.nes')
    ap.add_argument('--out', default='games/deep-dungeon-3/design/maps')
    a = ap.parse_args()
    rom = open(a.rom, 'rb').read()[16:]
    os.makedirs(a.out, exist_ok=True)
    txt = []
    for area, floors in AREAS.items():
        for fl, bank, off in floors:
            g = rom[bank * 0x4000 + off: bank * 0x4000 + off + 0x400]
            name = 'area%d_f%d' % (area, fl)
            draw(g, 32, 32, os.path.join(a.out, name + '.png'), 'Deep Dungeon III area %d floor %d (bank %d $%04X)' % (area, fl, bank, 0x8000 + off))
            specials = sorted({(v) for v in g if char(v) is None})
            txt.append('## %s (bank %d $%04X)\nother squares: %s\n```\n%s\n```\n' % (name, bank, 0x8000 + off, ' '.join('%02X' % v for v in specials), text(g, 32, 32)))
    bank, off, h = TOWN
    g = rom[bank * 0x4000 + off: bank * 0x4000 + off + 32 * h]
    draw(g, 32, h, os.path.join(a.out, 'towns.png'), 'Deep Dungeon III towns (bank 9 $9700, 32x48)')
    # town names (design/maps.md section 5): label at a square (x, y)
    im = Image.open(os.path.join(a.out, 'towns.png')); d = ImageDraw.Draw(im)
    for (x, y, t) in [(4, 21, 'NORTH TOWN (castle: 8)'), (1, 32, 'DIRIGE (start)'), (17, 30, 'AIL (tower: 7)'),
                      (9, 17, 'pocket')]:
        d.rectangle([24 + x * 16, 28 + y * 16 + 2, 24 + x * 16 + 6 * len(t) + 4, 28 + y * 16 + 13], fill=(0, 0, 0))
        d.text((24 + x * 16 + 2, 28 + y * 16 + 3), t, fill=(255, 255, 0))
    im.save(os.path.join(a.out, 'towns.png'))
    txt.append('## towns (bank 9 $9700)\n```\n%s\n```\n' % text(g, 32, h))
    open(os.path.join(a.out, 'grids.md'), 'w').write('# Deep Dungeon III - raw floor grids (generated by tools/maps.py)\n\n' + '\n'.join(txt))
    print('wrote', a.out)

if __name__ == '__main__':
    main()
