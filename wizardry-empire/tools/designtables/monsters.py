"""Generate the bestiary table and the encounter/floor tables from the original ROM.
Output: docs/design/monsters_table.md (written by this script) + work/design/monsters/floors.txt"""
import sys, json, collections
import os
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')) + '/'
sys.path.insert(0, os.path.join(ROOT, 'tools'))
r=open(ROOT+'rom/wizardry_empire_j.gbc','rb').read()
def rd(bank,addr,n): o=bank*0x4000+addr-0x4000; return r[o:o+n]
mons=json.load(open(ROOT+'script/monsters.json'))
en={m['id']+1:(m['en'],m['jp']) for m in mons}
recs=[rd(0x39,0x4820+64*k,64) for k in range(167)]
UNID=['?']*16
# encounter table: id -> 4 formation indices; formation -> 4 (monster,count) pairs
enc={i:list(rd(0x39,0x7A27+4*i,4)) for i in range(1,106)}
form={f:[(b[2*j],b[2*j+1]) for j in range(4)] for f,b in ((f,rd(0x39,0x7573+8*f,8)) for f in range(150))}
def cnt(c, first):
    hi,lo=c>>4,c&15
    a,b=hi,hi+(lo-1 if lo else 0)
    if first: a=max(a,1); b=max(b,1)
    return min(a,9),min(b,9)
# floors: which encounter ids appear on which floor (random: any square with b1; guarded = type 6)
floor_ids=collections.defaultdict(lambda: collections.Counter())
guard_ids=collections.defaultdict(lambda: collections.Counter())
for f in range(30):
    bank=0x3E+(f>>4); base=0x4000+0x400*(f&15)
    m=rd(bank,base,0x400)
    for i in range(256):
        c=m[i*4:i*4+4]; t=c[2]&0x3f
        if c[1]:
            if t==6: guard_ids[f+1][c[1]]+=1
            elif t in (0,):  floor_ids[f+1][c[1]]+=1
id_floors=collections.defaultdict(set); id_gfloors=collections.defaultdict(set)
for f,cn in floor_ids.items():
    for i in cn: id_floors[i].add(f)
for f,cn in guard_ids.items():
    for i in cn: id_gfloors[i].add(f)
mon_where=collections.defaultdict(lambda: [set(),set(),set()])  # random floors, guard floors, enc ids
for i,fs in enc.items():
    for fi in fs:
        if fi>=150: continue
        for k,(mid,c) in enumerate(form[fi]):
            if mid==0xFF or (k>0 and c==0): continue
            mon_where[mid][2].add(i)
            mon_where[mid][0]|=id_floors.get(i,set()); mon_where[mid][1]|=id_gfloors.get(i,set())
def rng(s):
    s=sorted(s)
    if not s: return ''
    out=[];a=b=s[0]
    for x in s[1:]:
        if x==b+1: b=x
        else: out.append((a,b)); a=b=x
    out.append((a,b))
    return ','.join(str(a) if a==b else '%d-%d'%(a,b) for a,b in out)
TYPE={1:'U',2:'D',4:'Dr',8:'S',16:'G',32:'Sp'}
def typ(v):
    t=[n for b,n in TYPE.items() if v&b]; return '+'.join(t) if t else '-'
SP=['M','P','A','?3','?4','?5']
def spells(b0,b1,b2):
    out=[]
    for i,v in enumerate([b0>>4,b0&15,b1>>4,b1&15,b2>>4,b2&15]):
        if v: out.append('s%d:L%d'%(i,v))
    return ' '.join(out) or '-'
SPEC=['poison','fear','sleep','paralyze','stone','decap','breath']
BREATH=['fire','frost','poison','lightning','acid','stone']
def specials(x):
    s=[n for i,n in enumerate(SPEC) if x[0x27]>>i&1]
    if x[0x27]&0x40: s[-1]='breath('+(BREATH[x[0x33]] if x[0x33]<6 else str(x[0x33]))+')'
    if x[0x28]: s.append('drain %d'%x[0x28])
    if x[0x29]>>4: s.append('call %d%%'%(65 if x[0x29]&0x80 else 25))
    if x[0x29]&15: s.append('flee %d%%'%((x[0x29]&15)*5))
    return ', '.join(s) or '-'
import tbl
lines=[]
lines.append('# Wizardry Empire bestiary (generated)\n')
lines.append('Generated by `python3 tools/designtables` from the original game data (Rev 1); do not edit by hand.')
lines.append('Rules behind each column: [monsters.md](monsters.md) and [combat.md](combat.md); record layout and evidence:')
lines.append('[../tech/monsters.md](../tech/monsters.md) §1. Columns:\n')
lines.append('- **id**: monster number (museum order). **EN/JP**: English and Japanese name.')
lines.append('- **Lv**: level. **HP**: hit point range (min-max). **AC**: armour class (lower = harder to hit).')
lines.append('- **Hit**: to-hit base (lower = more accurate). **Att**: attacks per round. **Dmg**: damage range per attack.')
lines.append('- **Reach**: 0 melee, 1 reach, 2 ranged. **Esc**: subtracted from the party\'s escape chance.')
lines.append('- **Type**: U undead, D demon, Dr dragon, S spirit (what slaying weapons check); G and Sp: two marks of unknown meaning.')
lines.append('- **Spells**: s0..s5 = spell school 0-5 (0 Mage, 1 Priest, 2-5 not named), L = highest spell level it casts.')
lines.append('- **Specials**: special attacks, level drain, call for help / flee chances, breath element. **Resist %**: chance to')
lines.append('  resist each element, order Earth/Water/Fire/Wind/Spirit/(6th)/Holy/None; "-" = no resistance.')
lines.append('- **EXP**, **Gold**: reward per kill. **Chest**: chest-value row the monster gives (see [dungeon.md](dungeon.md)).')
lines.append('- **Floors**: floors whose random encounters can produce it; **G**: floors where a guarded square can produce it.')
lines.append('  **Enc**: the encounter areas that include it (table below).\n')
lines.append('| id | EN | JP | Lv | HP | AC | Hit | Att | Dmg | Reach | Esc | Type | Spells | Specials | Resist % | EXP | Gold | Chest | Floors | G | Enc |')
lines.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for k,x in enumerate(recs):
    e,j=en.get(k,('?','?'))
    n,s,mn=x[0x15],x[0x16],x[0x17]
    hp='%d-%d'%(mn,mn+n*(s-1)) if n else str(mn)
    dn,ds,dm=x[0x12],x[0x13],x[0x14]
    dmg='%d-%d'%(dm,dm+dn*(ds-1)) if dn else str(dm)
    ac=x[0x23]-256 if x[0x23]>127 else x[0x23]
    res=[100-v for v in x[0x18:0x20]]
    rs='-' if all(v==0 for v in res) else '/'.join(str(v) for v in res)
    exp=x[0x30]|x[0x31]<<8|x[0x32]<<16
    gold=x[0x2E]|x[0x2F]<<8
    w=mon_where.get(k,[set(),set(),set()])
    lines.append('| %d | %s | %s | %d | %s | %d | %d | %d | %s | %d | %d | %s | %s | %s | %s | %d | %d | %d | %s | %s | %s |'%(
        k,e,j,x[0x25],hp,ac,x[0x10],x[0x11],dmg,x[0x2C]&3,x[0x24],typ(x[0x0E]),spells(x[0x20],x[0x21],x[0x22]),specials(x),rs,exp,gold,x[0x2D],rng(w[0]),rng(w[1]),rng(w[2])))
lines.append('\n## Encounter tables\n')
lines.append('Each encounter area lists 4 formations; a fight picks one of them at random. A formation is up to 4 monster groups,')
lines.append('written monster ×size (a range when the size is rolled; at most 9 per group). Rules: [monsters.md](monsters.md).\n')
lines.append('| enc id | random on floors | guarded squares on floors | formation (one of 4 picked at random; monster ×size) |')
lines.append('|---|---|---|---|')
def fstr(fi):
    if fi>=150: return '(none)'
    out=[]
    for k,(mid,c) in enumerate(form[fi]):
        if mid==0xFF: continue
        a,b=cnt(c,k==0)
        if b==0: continue
        out.append('%s ×%s'%(en.get(mid,('#%d'%mid,))[0], str(a) if a==b else '%d-%d'%(a,b)))
    return ' + '.join(out)
for i,fs in enc.items():
    if not any(fs): continue
    fl=rng(id_floors.get(i,set())); gf=rng(id_gfloors.get(i,set()))
    uniq=[]
    for fi in fs:
        if fi not in uniq: uniq.append(fi)
    lines.append('| %d | %s | %s | %s |'%(i,fl,gf,' / '.join('F%d: %s'%(fi,fstr(fi)) for fi in uniq)))
open(ROOT+'docs/design/monsters_table.md','w').write('\n'.join(lines)+'\n')
# floor summary
os.makedirs(ROOT+'work/design/monsters', exist_ok=True)
with open(ROOT+'work/design/monsters/floors.txt','w') as f:
    for fl in range(1,31):
        f.write('F%d random ids %s guarded ids %s\n'%(fl,dict(floor_ids[fl]),dict(guard_ids[fl])))
print('ok')
